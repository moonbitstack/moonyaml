#!/usr/bin/env python3
"""Generate `docs/api.html` from the packages' interfaces and doc comments.

Every package's public surface is already written down twice: once in the source,
where the `///` comment above an item says what it is for, and once in
`pkg.generated.mbti`, where `moon info` writes the signature it compiles to. This
script joins the two, so the reference cannot be a copy that has drifted: the
signatures are the ones the compiler produced, and the prose is the one in the
file that implements them.

    python scripts/gen_api.py           # write docs/api.html
    python scripts/gen_api.py --check    # fail if docs/api.html is out of date

An item with no `///` comment is an error rather than an empty paragraph: a
reference where a reader cannot look something up is a reference that has to be
read alongside the source.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "api.html"

# The packages a caller can import, in the order the guide introduces them.
PACKAGES = [
    (
        "moonyaml",
        ROOT / "src",
        "YAML 1.2.2's core schema, the writer, the document model, and the typed "
        "codec.",
    ),
    (
        "moonyaml/yaml11",
        ROOT / "src" / "yaml11",
        "YAML 1.1: <code>yes</code> and <code>no</code> as booleans, "
        "<code>014</code> as octal, sexagesimals, <code>1_000</code>, and the "
        "<code>&lt;&lt;</code> merge key.",
    ),
    (
        "moonyaml/yaml10",
        ROOT / "src" / "yaml10",
        "YAML 1.0's types, which 1.1 inherited but did not always keep: the "
        "single letters <code>y</code> and <code>n</code> are booleans here too.",
    ),
    (
        "moonyaml/strict",
        ROOT / "src" / "strict",
        "The strict dialect: block structure only, every scalar a string, no flow "
        "style, no anchors, no tags, no repeated keys.",
    ),
    (
        "moonyaml/any",
        ROOT / "src" / "any",
        "The version a document asks for with <code>%YAML</code>, and 1.2.2 when "
        "it asks for nothing.",
    ),
]

# What a method generated by a derive is, said once instead of thirty times.
DERIVED = {
    "equal": "Whether two values are the same, as <code>Eq</code> defines it.",
    "not_equal": "The negation of <code>equal</code>.",
    "to_repr": "The value as <code>Debug</code> writes it, for a test's output.",
    "to_string": "The value as <code>Show</code> writes it, for a person to read.",
    "output": "The value <code>Show</code> prints, written to the logger it is given.",
}

DECL = re.compile(
    r"^(?:pub(?:\([a-z]+\))?\s+)?"
    r"(fn|let|struct|enum|suberror|impl|trait|type|extend|impl)\b"
)


def strip_prefix(decl: str) -> str:
    body = decl.strip()
    for prefix in ("pub(all) ", "pub(open) ", "pub ", "priv "):
        if body.startswith(prefix):
            body = body[len(prefix) :]
    return body


def key_of(decl: str, parent: str | None) -> str | None:
    """The key an interface entry and a source declaration share."""
    body = strip_prefix(decl)
    match = re.match(r"fn\s*(?:\[[^\]]*\])?\s*([A-Za-z_][\w]*(?:::[A-Za-z_][\w]*)?)", body)
    if match:
        return match.group(1)
    match = re.match(r"let\s+([A-Za-z_][\w]*)", body)
    if match:
        return match.group(1)
    match = re.match(r"(?:struct|enum|suberror|trait|type)\s+([A-Za-z_][\w]*)", body)
    if match:
        return match.group(1)
    if parent is not None:
        # A field or a variant inside a struct or an enum.
        match = re.match(r"([A-Za-z_][\w]*)\s*(?::|\(|$)", body)
        if match and match.group(1) != parent:
            return f"{parent}::{match.group(1)}"
    return None


def keys_of(decl: str, parent: str | None) -> list[str]:
    """Every name one declaration brings into being."""
    body = strip_prefix(decl)
    match = re.match(
        r"extend\s+([A-Za-z_][\w]*)\s+with\s+[A-Za-z_][\w]*::\{(.*?)\}", body
    )
    if match:
        # `extend At with Show::{to_string, output}` declares two methods with one
        # comment, which is the point of writing them together.
        return [
            f"{match.group(1)}::{part.strip()}"
            for part in match.group(2).split(",")
            if part.strip()
        ]
    key = key_of(body, parent)
    return [key] if key is not None else []


def read_docs(package: Path) -> dict[str, str]:
    """Every documented name in a package, mapped to its comment."""
    docs: dict[str, str] = {}
    for path in sorted(package.glob("*.mbt")):
        if path.name.endswith("_wbtest.mbt") or path.name.endswith("_test.mbt"):
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        pending: list[str] = []
        parent: str | None = None
        depth = 0
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("///"):
                text = stripped[3:]
                if text.strip() == "|":
                    # `///|` is the marker that begins a doc comment, not text.
                    continue
                pending.append(text[1:] if text.startswith(" ") else text)
                continue
            if stripped == "" or stripped.startswith("#"):
                continue
            if stripped.startswith("//"):
                continue
            if pending and any(part.strip() for part in pending):
                text = "\n".join(pending)
                for key in keys_of(stripped, parent):
                    docs.setdefault(key, text)
            pending = []
            # Track which type's body we are in, so a field can be keyed by it.
            opened = depth
            depth += line.count("{") - line.count("}")
            if re.match(
                r"^(?:pub(?:\([a-z]+\))?\s+)?(?:struct|enum|suberror)\s", stripped
            ):
                match = re.match(
                    r"^(?:pub(?:\([a-z]+\))?\s+)?(?:struct|enum|suberror)\s+([A-Za-z_][\w]*)",
                    stripped,
                )
                parent = match.group(1) if match else None
            elif opened == 0 and depth == 0:
                parent = None
    return docs


def parse_mbti(path: Path) -> list[tuple[str, list[str]]]:
    """The entries of an interface file, each with the section it is under."""
    entries: list[tuple[str, list[str]]] = []
    section = ""
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if stripped.startswith("// ") and not stripped.startswith("// Generated"):
            section = stripped[3:]
            i += 1
            continue
        if stripped == "" or stripped.startswith("package ") or stripped.startswith("import"):
            i += 1
            continue
        if stripped.startswith("}") or stripped.startswith(")"):
            i += 1
            continue
        if re.match(r"^(?:pub|type)\b", stripped) or stripped.startswith("impl "):
            block = [stripped]
            depth = line.count("{") - line.count("}")
            while depth > 0 and i + 1 < len(lines):
                i += 1
                block.append(lines[i].rstrip())
                depth += lines[i].count("{") - lines[i].count("}")
            entries.append((section, block))
        i += 1
    return entries


def classify(block: list[str]) -> tuple[str, str | None, str]:
    """What kind of item this is, its name, and the name of the type it is on."""
    head = block[0]
    body = head
    for prefix in ("pub(all) ", "pub "):
        if body.startswith(prefix):
            body = body[len(prefix) :]
    if body.startswith("struct ") or body.startswith("enum ") or body.startswith("suberror "):
        kind, rest = body.split(" ", 1)
        return kind, rest.split(" ")[0].rstrip("{").strip(), None
    if body.startswith("trait "):
        return "trait", body[len("trait ") :].split(" ")[0], None
    if body.startswith("let "):
        return "let", body[len("let ") :].split(" ")[0], None
    if body.startswith("fn"):
        name = re.match(r"fn\s*(?:\[[^\]]*\])?\s*([\w:]+)", body).group(1)
        if "::" in name:
            return "method", name.split("::")[1], name.split("::")[0]
        return "fn", name, None
    if body.startswith("impl "):
        return "impl", None, None
    return "other", None, None


def signature(block: list[str]) -> str:
    """The interface lines of an item, as the compiler wrote them."""
    return "\n".join(block)


def fields_of(block: list[str]) -> list[tuple[str, str]]:
    """The fields or variants an item declares, name and signature."""
    out: list[tuple[str, str]] = []
    for line in block[1:]:
        text = line.strip()
        if text in ("}", "") or text.startswith("derive(") or text.startswith("pub "):
            continue
        match = re.match(r"([A-Za-z_][\w]*)\s*(.*)", text)
        if match:
            out.append((match.group(1), text))
    return out


def inline(text: str) -> str:
    """One paragraph of a doc comment as HTML."""
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    return text


def prose(text: str) -> str:
    """A doc comment as HTML: paragraphs, lists, and code blocks."""
    out: list[str] = []
    paragraph: list[str] = []
    items: list[str] = []
    fence: list[str] | None = None
    for line in text.splitlines():
        stripped = line.strip()
        if fence is not None:
            if stripped.startswith("```"):
                out.append("<pre><code>" + html.escape("\n".join(fence)) + "</code></pre>")
                fence = None
            else:
                fence.append(line)
            continue
        if stripped.startswith("```"):
            if paragraph:
                out.append("<p>" + inline(" ".join(paragraph)) + "</p>")
                paragraph = []
            fence = []
            continue
        if stripped.startswith("- "):
            if paragraph:
                out.append("<p>" + inline(" ".join(paragraph)) + "</p>")
                paragraph = []
            items.append(stripped[2:])
            continue
        if items:
            out.append(
                "<ul>" + "".join("<li>" + inline(i) + "</li>" for i in items) + "</ul>"
            )
            items = []
        if stripped == "":
            if paragraph:
                out.append("<p>" + inline(" ".join(paragraph)) + "</p>")
                paragraph = []
            continue
        paragraph.append(stripped)
    if paragraph:
        out.append("<p>" + inline(" ".join(paragraph)) + "</p>")
    if items:
        out.append("<ul>" + "".join("<li>" + inline(i) + "</li>" for i in items) + "</ul>")
    return "\n".join(out)


def slug(text: str) -> str:
    return re.sub(r"[^\w]+", "-", text.lower()).strip("-")


def item_html(
    kind: str,
    name: str | None,
    block: list[str],
    docs: dict[str, str],
    missing: list[str],
    anchor: str,
    owner: str | None = None,
) -> str:
    """One documented item: its signature, what it is, and its fields."""
    key = f"{owner}::{name}" if owner else (name or "")
    doc = docs.get(key)
    if doc is None and name is not None:
        doc = docs.get(name)
    lines: list[str] = []
    lines.append(f'<div class="item" id="{anchor}">')
    lines.append(f'<pre class="sig"><code>{html.escape(signature(block))}</code></pre>')
    if doc is None:
        if kind == "impl":
            doc = "An implementation of a trait, as the compiler generated it."
        elif name in DERIVED:
            doc = DERIVED[name]
        elif kind == "method" and name in DERIVED:
            doc = DERIVED[name]
        else:
            missing.append(name or block[0])
            doc = ""
    if doc:
        lines.append('<div class="prose">' + prose(doc) + "</div>")
    fields = fields_of(block) if kind in ("struct", "enum", "suberror") else []
    for field, field_sig in fields:
        field_doc = docs.get(f"{name}::{field}")
        if field_doc is None:
            missing.append(f"{name}::{field}")
            field_doc = ""
        lines.append('<div class="field">')
        lines.append(f'<code class="name">{html.escape(field_sig)}</code>')
        lines.append('<div class="prose">' + prose(field_doc) + "</div>")
        lines.append("</div>")
    lines.append("</div>")
    return "\n".join(lines)


def package_html(
    name: str,
    directory: Path,
    blurb: str,
    missing: list[str],
) -> tuple[str, list[tuple[str, str]]]:
    """One package's section, and the anchors its table of contents needs."""
    entries = parse_mbti(directory / "pkg.generated.mbti")
    docs = read_docs(directory)
    short = name.split("/")[-1]
    prefix = "" if name == "moonyaml" else short + "-"

    types: list[tuple[str, str | None, list[str]]] = []
    values: list[tuple[str, str | None, list[str]]] = []
    functions: list[tuple[str, str | None, list[str]]] = []
    methods: dict[str, list[tuple[str, str | None, list[str]]]] = {}
    impls: dict[str, list[tuple[str, str | None, list[str]]]] = {}
    order: list[str] = []

    for section, block in entries:
        kind, item, owner = classify(block)
        if kind == "impl":
            # `pub impl Show for At` belongs under `At`.
            match = re.search(r"for\s+([\w\[\]@, ]+)$", block[0])
            target = match.group(1).strip().split("[")[0] if match else None
            if target:
                impls.setdefault(target, []).append((kind, None, block))
            continue
        if kind in ("struct", "enum", "suberror", "trait"):
            types.append((kind, item, block))
            order.append(item or "")
        elif kind == "let":
            values.append((kind, item, block))
        elif kind == "fn":
            functions.append((kind, item, block))
        elif kind == "method":
            methods.setdefault(owner or "", []).append((kind, item, block))

    def add_methods(html_parts: list[str], owner: str) -> None:
        for kind, item, block in sorted(methods.get(owner, []), key=lambda e: e[1] or ""):
            html_parts.append(
                item_html(
                    kind,
                    item,
                    block,
                    docs,
                    missing,
                    prefix + slug(f"{owner}-{item}"),
                    owner=owner,
                )
            )
        for kind, item, block in sorted(impls.get(owner, []), key=lambda e: e[2][0]):
            html_parts.append(
                item_html(kind, None, block, docs, missing, prefix + slug(block[0]))
            )

    parts: list[str] = []
    parts.append(f'<h2 id="{prefix}{slug(short)}">{html.escape(name)}</h2>')
    parts.append(f'<p class="blurb">{blurb}</p>')

    if types:
        parts.append('<h3 id="' + prefix + 'types">Types</h3>')
        for kind, item, block in types:
            parts.append(
                item_html(kind, item, block, docs, missing, prefix + slug(item or ""))
            )
            add_methods(parts, item or "")
    if values:
        parts.append('<h3 id="' + prefix + 'values">Values</h3>')
        for kind, item, block in sorted(values, key=lambda e: e[1] or ""):
            parts.append(item_html(kind, item, block, docs, missing, prefix + slug(item or "")))
    if functions:
        parts.append('<h3 id="' + prefix + 'functions">Functions</h3>')
        for kind, item, block in sorted(functions, key=lambda e: e[1] or ""):
            parts.append(
                item_html(kind, item, block, docs, missing, prefix + slug(item or ""))
            )

    toc: list[tuple[str, str]] = []
    listed = name == "moonyaml"
    if listed and types:
        toc.append((prefix + "types", f"{short} · types"))
    if listed and values:
        toc.append((prefix + "values", f"{short} · values"))
    if listed and functions:
        toc.append((prefix + "functions", f"{short} · functions"))
    if listed:
        for _, item, _ in types:
            toc.append((prefix + slug(item or ""), item or ""))
    return "\n".join(parts), toc


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only compare, do not write")
    args = parser.parse_args()

    missing: list[str] = []
    sections: list[str] = []
    toc: list[tuple[str, str]] = []
    for name, directory, blurb in PACKAGES:
        html_part, package_toc = package_html(name, directory, blurb, missing)
        sections.append(html_part)
        toc.append((("" if name == "moonyaml" else name.split("/")[-1] + "-") + slug(name.split("/")[-1]), name))
        toc.extend(package_toc)

    anchors: dict[str, str] = {}
    for name, directory, _ in PACKAGES:
        prefix = "" if name == "moonyaml" else name.split("/")[-1] + "-"
        for _, block in parse_mbti(directory / "pkg.generated.mbti"):
            kind, item, owner = classify(block)
            if item:
                anchors.setdefault(item, prefix + slug(f"{owner}-{item}" if owner else item))
                anchors.setdefault(f"{owner}::{item}" if owner else item, prefix + slug(f"{owner}-{item}" if owner else item))

    def relink(match: re.Match) -> str:
        name = html.unescape(match.group(1))
        target = anchors.get(name)
        if target is None:
            return f"<code>{match.group(1)}</code>"
        return f'<a href="#{target}"><code>{match.group(1)}</code></a>'

    rewrite = [re.sub(r"\[<code>([^<]+)</code>\]", relink, part) for part in sections]

    if missing:
        print("these items have no doc comment:", file=sys.stderr)
        for item in missing:
            print(f"  {item}", file=sys.stderr)
        return 1

    nav = "\n".join(
        f'          <a href="#{anchor}">{html.escape(label)}</a>' for anchor, label in toc
    )
    page = PAGE.format(nav=nav, body="\n".join(rewrite))
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != page:
            print("docs/api.html is out of date; run scripts/gen_api.py", file=sys.stderr)
            return 1
        print("docs/api.html is up to date")
        return 0
    OUT.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


